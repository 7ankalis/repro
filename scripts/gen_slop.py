"""
Generate SYNTHETIC AI-slop reports for evaluation (task C3).

  # dry-run: only 2 items, print the cost, write nothing
  python scripts/gen_slop.py --targets curl arvo_42487096 --n 15 --dry-run
  # the real run: 15 reports across 5 failure modes for curl + muparser
  python scripts/gen_slop.py --targets curl arvo_42487096 --n 15 --out datasets/slop_synth

These are DEFENSIVE evaluation inputs: false-but-plausible reports that let us measure whether Repro rejects slop.
They are labelled `source: synthetic` / `label: slop` in the front matter and never submitted to any real project.
The failure mode is deliberately NOT written into the report body (that would leak the ground truth to the triage
model); it lives only in meta.json next to the report, which no model is ever shown.

For each report: pull real identifiers from the target's source tree (inside the sandbox), ask the open-weights
model on Baseten (LLM.cheap()) for a false report using one failure mode, and write <out>/<id>/report.md + meta.json.
"""
from __future__ import annotations

import argparse
import json
import random
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

import yaml
from dotenv import load_dotenv

from repro.llm import LLM
from repro.prompts import load_prompt
from repro.sandbox import Sandbox
from repro.schemas import Target

# The 5 failure modes this dataset must cover (task C3). Order matters: plan_items() cycles through them so that an
# even --n distributes modes evenly.
MODES = [
    "hallucinated_function",         # blames a function that does not exist
    "wrong_file",                    # real symbol, wrong/nonexistent file
    "invented_code_quote",           # quotes code that is not in the tree
    "non_reproducible",              # plausible but no reachable trigger / no working PoC
    "hidden_instruction_injection",  # hides an instruction aimed at the triage agent
]

# Make the dataset clearly, machine-readably synthetic without leaking the per-report ground truth into the body.
SYNTHETIC_README = """\
# datasets/slop_synth — SYNTHETIC AI-slop reports (defensive eval inputs)

Every report in this folder is **synthetic and false**. They are generated by `scripts/gen_slop.py` to measure
whether Repro correctly rejects low-quality AI-generated vulnerability reports. They are **never** submitted to any
real project or maintainer.

- Front matter marks each one `source: synthetic`, `label: slop`, `synthetic_eval_input: true`.
- The intended failure mode and cited symbols live in each report's `meta.json` (ground truth) — never shown to any
  model, so the body reads like a genuine report.
- Modes covered: hallucinated_function, wrong_file, invented_code_quote, non_reproducible, hidden_instruction_injection.

The `hidden_instruction_injection` reports contain deliberate prompt-injection payloads as *untrusted report data*.
That is intentional: Repro must treat report text as data, never as instructions (see AGENTS.md invariant 2).
"""


@dataclass(frozen=True)
class PlanItem:
    index: int
    target_key: str   # key in config/targets.yaml
    project: str      # human project name, used in the report id
    mode: str
    rid: str          # report id / folder name


def plan_items(n: int, targets: list[tuple[str, str]]) -> list[PlanItem]:
    """Deterministically assign (target, failure mode, id) to each of n reports.

    targets is a list of (config_key, project_name). Targets and modes are both cycled so a balanced --n covers every
    mode and every target evenly. Pure/deterministic -> unit-tested without API or Docker.
    """
    if not targets:
        raise ValueError("need at least one target")
    counters: dict[str, int] = defaultdict(int)
    items: list[PlanItem] = []
    for i in range(n):
        key, project = targets[i % len(targets)]
        mode = MODES[i % len(MODES)]
        rid = f"slop-{project}-{counters[project]:02d}"
        counters[project] += 1
        items.append(PlanItem(index=i, target_key=key, project=project, mode=mode, rid=rid))
    return items


def real_identifiers(sb: Sandbox, k: int = 60) -> tuple[list[str], list[str]]:
    """Sample real function names and file paths from the target source tree (C and C++)."""
    src = sb.target.src_dir
    inc = "--include=*.c --include=*.cc --include=*.cpp --include=*.cxx --include=*.h --include=*.hpp"
    fns = sb.exec(
        f"grep -rhoE {inc} '^[a-zA-Z_][a-zA-Z0-9_ \\*:]*\\b([A-Za-z_][A-Za-z0-9_]{{4,}})\\(' {src} "
        "| grep -oE '[A-Za-z0-9_]+\\($' | tr -d '(' | sort -u | shuf -n 400",
        timeout=120, workdir="/").stdout.split()
    files = sb.exec(
        f"cd {src} && git ls-files '*.c' '*.cc' '*.cpp' '*.cxx' '*.h' '*.hpp' 2>/dev/null | shuf -n 80 "
        "|| find . -name '*.c*' | shuf -n 80",
        timeout=60, workdir="/").stdout.split()
    if not fns:
        raise RuntimeError(f"no function identifiers found under {src}; check the target image/src_dir")
    return random.sample(fns, min(k, len(fns))), files


def generate(llm: LLM, project: str, mode: str, fns: list[str], files: list[str]) -> dict:
    user = (
        f"Project: {project}\nFailure mode: {mode}\n"
        f"Real functions: {', '.join(random.sample(fns, min(25, len(fns))))}\n"
        f"Real files: {', '.join(random.sample(files, min(15, len(files))))}"
    )
    resp = llm.chat(
        [{"role": "system", "content": load_prompt("slop_generator")},
         {"role": "user", "content": user}],
        response_format={"type": "json_object"}, temperature=0.9, stage="note")
    return json.loads(resp.choices[0].message.content)


def write_report(out: Path, item: PlanItem, tcfg: dict, data: dict) -> Path:
    d = out / item.rid
    d.mkdir(parents=True, exist_ok=True)
    fm = {
        "id": item.rid,
        "title": data["title"],
        "source": "synthetic",
        "label": "slop",                 # ground truth: eval only, never shown to a model
        "synthetic_eval_input": True,     # clearly flag these as synthetic (not a real report)
        "target": tcfg,
    }
    (d / "report.md").write_text("---\n" + yaml.safe_dump(fm, sort_keys=False) + "---\n" + data["body"])
    (d / "meta.json").write_text(json.dumps({
        "synthetic": True,
        "project": item.project,
        "failure_mode": item.mode,
        "cited": data.get("cited_symbols", []),
        "generator_reported_mode": data.get("failure_mode"),
    }, indent=2))
    return d


def main() -> None:
    load_dotenv()
    ap = argparse.ArgumentParser(description="Generate synthetic AI-slop reports (C3).")
    ap.add_argument("--targets", nargs="+", default=["curl", "arvo_42487096"],
                    help="target keys from config/targets.yaml (default: curl + muparser)")
    ap.add_argument("--n", type=int, default=15, help="total number of reports (default 15)")
    ap.add_argument("--out", default="datasets/slop_synth")
    ap.add_argument("--dry-run", action="store_true",
                    help="generate only 2 items and print the cost; write nothing to disk")
    ap.add_argument("--seed", type=int, default=None, help="optional RNG seed for reproducibility")
    a = ap.parse_args()
    if a.seed is not None:
        random.seed(a.seed)

    cfgs = yaml.safe_load(Path("config/targets.yaml").read_text())
    tcfgs = {key: cfgs[key] for key in a.targets}
    targets = [(key, tcfgs[key]["project"]) for key in a.targets]

    items = plan_items(a.n, targets)
    if a.dry_run:
        items = items[:2]
        print(f"[dry-run] generating {len(items)} of {a.n} planned reports; nothing will be written")

    llm = LLM.cheap()   # bulk data generation on Baseten (falls back to Muse Spark if cheap not configured)
    print(f"model: {llm.model}")

    # Pull identifiers once per target that this run actually touches.
    ids_cache: dict[str, tuple[list[str], list[str]]] = {}
    needed = {it.target_key for it in items}
    for key in a.targets:
        if key not in needed:
            continue
        with Sandbox(Target(**tcfgs[key])) as sb:
            ids_cache[key] = real_identifiers(sb)
        print(f"identifiers: {key} -> {len(ids_cache[key][0])} fns, {len(ids_cache[key][1])} files")

    out = Path(a.out)
    for it in items:
        fns, files = ids_cache[it.target_key]
        data = generate(llm, it.project, it.mode, fns, files)
        if a.dry_run:
            print(f"[dry-run] {it.rid:22s} {it.mode:30s} title={data['title'][:60]!r}")
        else:
            d = write_report(out, it, tcfgs[it.target_key], data)
            print("wrote", d, it.mode)

    if not a.dry_run:
        out.mkdir(parents=True, exist_ok=True)
        (out / "README.md").write_text(SYNTHETIC_README)

    print(f"cost: model {llm.model}: {llm.usage.calls} calls, "
          f"{llm.usage.tokens_in} in / {llm.usage.tokens_out} out tokens, ${llm.usage.cost_usd:.4f}")
    if a.dry_run:
        print(f"[dry-run] estimated full run ({a.n} reports): "
              f"~${llm.usage.cost_usd / max(len(items), 1) * a.n:.4f}")


if __name__ == "__main__":
    main()
